#!/usr/bin/env python3
"""Keep every stack version pin in line with ``versions.json``.

``versions.json`` at the repository root is the single source of truth for the
core stack versions. Each component lists the places that pin it (a set of
tracked files and a regular expression whose ``v`` group is the version). The
script either rewrites those pins and ``VERSIONS.md`` from the manifest
(``--write``) or fails when any pin or ``VERSIONS.md`` disagrees (``--check``).

Run it through ``scripts/sync-versions.sh`` from anywhere in the repository.
"""

from __future__ import annotations

import fnmatch
import json
import re
import subprocess
import sys
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from pathlib import Path

MANIFEST = "versions.json"
VERSIONS_MD = "VERSIONS.md"


def _same(version: str) -> str:
    return version


def _py_nodot(version: str) -> str:
    # ruff's target-version spells Python 3.14 as py314.
    return version.replace(".", "")


@dataclass(frozen=True)
class Pin:
    """One kind of version pin: the files it lives in and how to find it.

    Attributes:
        globs: fnmatch patterns over tracked paths.
        pattern: Regular expression with a named group ``v`` around the version.
        render: Maps the manifest version to the text expected in the ``v`` group.
        exclude: fnmatch patterns removed from the matched paths.
        writable: False when the pin is generated by a tool (a lockfile) and
            ``--write`` can only report it.
    """

    globs: tuple[str, ...]
    pattern: str
    render: Callable[[str], str] = _same
    exclude: tuple[str, ...] = ()
    writable: bool = True


@dataclass(frozen=True)
class Component:
    """A stack component tracked in ``versions.json``."""

    key: str
    name: str
    pins: tuple[Pin, ...] = field(default_factory=tuple)


