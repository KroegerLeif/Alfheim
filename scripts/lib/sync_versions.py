def repo_root() -> Path:
    """Return the root of the git checkout the script runs in."""
    out = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True)
    return Path(out.strip())


def tracked_files(root: Path) -> list[str]:
    """Return every tracked path, relative to the repository root."""
    out = subprocess.check_output(["git", "ls-files"], cwd=root, text=True)
    return out.split()


def files_for(pin: Pin, tracked: list[str]) -> list[str]:
    """Return the tracked paths a pin applies to, in a stable order."""
    hits = {p for p in tracked for g in pin.globs if fnmatch.fnmatchcase(p, g)}
    return sorted(p for p in hits if not any(fnmatch.fnmatchcase(p, x) for x in pin.exclude))


def load_manifest(root: Path, components: Sequence[Component] = COMPONENTS) -> dict[str, str]:
    """Read versions.json and make sure it names exactly the known components."""
    data = json.loads((root / MANIFEST).read_text())
    known = {c.key for c in components}
    if set(data) != known:
        missing, extra = sorted(known - set(data)), sorted(set(data) - known)
        raise SystemExit(f"{MANIFEST}: missing keys {missing}, unknown keys {extra}")
    return {k: str(v) for k, v in data.items()}


def render_versions_md(
    manifest: dict[str, str], pinned: dict[str, set[str]], components: Sequence[Component] = COMPONENTS
) -> str:
    """Build the VERSIONS.md table from the manifest and the files that pin each component."""
    lines = [
        "# Stack versions",
        "",
        "<!-- Generated by scripts/sync-versions.sh from versions.json. Do not edit by hand. -->",
        "",
        "The core stack versions of this branch. [`versions.json`](versions.json) is the single source",
        "of truth; `./scripts/sync-versions.sh --check` (part of `./scripts/verify.sh --security` and",
        "the `ci-required` check) fails when a pin below disagrees with it.",
        "",
        "| Component | Version | Pinned in |",
        "| --- | --- | --- |",
    ]
    for comp in components:
        count = len(pinned.get(comp.key, set()))
        lines.append(f"| {comp.name} | `{manifest[comp.key]}` | {count} file{'s' if count != 1 else ''} |")
    lines += ["", "## Where each version is pinned", ""]
    for comp in components:
        paths = sorted(pinned.get(comp.key, set()))
        lines.append(f"- **{comp.name}:** " + ", ".join(f"`{p}`" for p in paths))
    lines += [
        "",
        "## Changing a version",
        "",
        "Edit `versions.json`, run `./scripts/sync-versions.sh --write`, then `uv lock` or `pnpm install`",
        "when the Python or Next.js version changed, and run the gates.",
        "",
    ]
    return "\n".join(lines)


def sync(root: Path, write: bool, components: Sequence[Component] = COMPONENTS) -> list[str]:
    """Check or rewrite every pin; return the problems that remain."""
    manifest = load_manifest(root, components)
    tracked = tracked_files(root)
    problems: list[str] = []
    pinned: dict[str, set[str]] = {}
    for comp in components:
        want_raw = manifest[comp.key]
        for pin in comp.pins:
            want = pin.render(want_raw)
            regex = re.compile(pin.pattern)
            matched = False
            for rel in files_for(pin, tracked):
                path = root / rel
                text = path.read_text()
                found = list(regex.finditer(text))
                if not found:
                    continue
                matched = True
                pinned.setdefault(comp.key, set()).add(rel)
                wrong = [m for m in found if m.group("v") != want]
                if not wrong:
                    continue
                if write and pin.writable:
                    for m in reversed(wrong):
                        text = text[: m.start("v")] + want + text[m.end("v") :]
                    path.write_text(text)
                    continue
                for m in wrong:
                    line = text.count("\n", 0, m.start()) + 1
                    hint = "" if pin.writable else " (regenerate the lockfile)"
                    problems.append(f"{rel}:{line}: {comp.name} is {m.group('v')}, versions.json says {want}{hint}")
            if not matched:
                problems.append(f"{comp.name}: pattern {pin.pattern!r} matched no file in {pin.globs}")
    md = render_versions_md(manifest, pinned, components)
    md_path = root / VERSIONS_MD
    current = md_path.read_text() if md_path.exists() else ""
    if current != md:
        if write:
            md_path.write_text(md)
        else:
            problems.append(f"{VERSIONS_MD} is out of date; run ./scripts/sync-versions.sh --write")
    return problems


def main(argv: list[str]) -> int:
    """Parse ``--check`` or ``--write`` and report the result."""
    if len(argv) != 1 or argv[0] not in ("--check", "--write"):
        print("Usage: sync-versions.sh --check | --write", file=sys.stderr)
        return 2
    problems = sync(repo_root(), write=argv[0] == "--write")
    for p in problems:
        print(f"✖ {p}", file=sys.stderr)
    if problems:
        return 1
    print(
        "✔ Every version pin matches versions.json"
        + (" (pins and VERSIONS.md written)" if argv[0] == "--write" else "")
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
