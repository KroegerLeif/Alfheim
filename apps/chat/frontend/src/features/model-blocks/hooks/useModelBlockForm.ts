"use client";

import { useState, useRef } from "react";
import type { CreateModelBlockRequest, ModelBlock, UpdateModelBlockRequest } from "../types";

/** Payload the model block form submits: a create request or an update for an existing block. */
export type ModelBlockFormPayload = CreateModelBlockRequest | { id: string; payload: UpdateModelBlockRequest };

/** Field values and handlers of the model block form, as returned by {@link useModelBlockForm}. */
export type ModelBlockFormState = ReturnType<typeof useModelBlockForm>;

/**
 * Owns the model block form state and builds the create or update payload on submit.
 */
export function useModelBlockForm(model: ModelBlock | null | undefined, onSubmit: (payload: ModelBlockFormPayload) => void) {
  const isEditing = !!model;

  const [displayName, setDisplayName] = useState(model?.display_name ?? "");
  const [providerType, setProviderType] = useState(model?.provider_type ?? "ollama");
  const [modelIdentifier, setModelIdentifier] = useState(model?.model_identifier ?? "");
  const [baseUrl, setBaseUrl] = useState(model?.base_url ?? "");
  const [apiKey, setApiKey] = useState("");
  const [visibility, setVisibility] = useState<"private" | "shared">(model?.visibility ?? "private");

  const autoGeneratedNameRef = useRef<string>("");

  // A stored key is never reused for a different endpoint (the server enforces this),
  // so changing the URL of a keyed block without entering a new key drops the old one.
  const normalizeUrl = (value: string) => value.trim().replace(/\/+$/, "").toLowerCase();
  const dropsStoredKey =
    isEditing && !!model?.has_api_key && !apiKey && normalizeUrl(baseUrl) !== normalizeUrl(model.base_url ?? "");

  const handleModelSelect = (identifier: string, autoDisplayName?: string) => {
    setModelIdentifier(identifier);
    if (autoDisplayName && (!displayName || displayName === autoGeneratedNameRef.current)) {
      setDisplayName(autoDisplayName);
      autoGeneratedNameRef.current = autoDisplayName;
    }
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (isEditing && model) {
      onSubmit({
        id: model.id,
        payload: {
          display_name: displayName,
          model_identifier: modelIdentifier,
          base_url: baseUrl || undefined,
          api_key: apiKey || undefined,
          clear_api_key: dropsStoredKey || undefined,
          visibility,
        },
      });
    } else {
      onSubmit({
        display_name: displayName,
        provider_type: providerType,
        model_identifier: modelIdentifier,
        base_url: baseUrl || undefined,
        api_key: apiKey || undefined,
        visibility,
      });
    }
  };

  return {
    isEditing,
    displayName,
    setDisplayName,
    providerType,
    setProviderType,
    modelIdentifier,
    baseUrl,
    setBaseUrl,
    apiKey,
    setApiKey,
    visibility,
    setVisibility,
    dropsStoredKey,
    handleModelSelect,
    handleSubmit,
  };
}
