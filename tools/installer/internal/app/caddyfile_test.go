// setStrategy records the TLS strategy in the install's .env, like a Day-1
// install does.
func setStrategy(t *testing.T, dir, strategy string) {
	t.Helper()
	if err := envfile.Update(filepath.Join(dir, ".env"), map[string]string{
		"ALFHEIM_TLS_STRATEGY": strategy,
	}); err != nil {
		t.Fatal(err)
	}
}

func caddyRestarts(app *UpdateApp) int {
	n := 0
	for _, c := range app.Runner.(interface{ Calls() []runner.Command }).Calls() {
		args := strings.Join(c.Args, " ")
		if c.Name == "docker" && strings.Contains(args, "restart") && strings.Contains(args, "caddy") {
			n++
		}
	}
	return n
}

func TestUpdateApp_RerendersCaddyfileFromStoredConfig(t *testing.T) {
	dir := t.TempDir()
	writeExistingInstall(t, dir, "v1.0.0")
	setStrategy(t, dir, "internal")

	caddyfile := filepath.Join(dir, "infrastructure", "caddy", "Caddyfile")
	if err := os.MkdirAll(filepath.Dir(caddyfile), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(caddyfile, []byte("# stale caddyfile from the first install\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	srv := startAssetServer(t, updateAssetContents("v1.1.0"))
	defer srv.Close()
	app, _, stderr := newTestUpdateApp(dir, &UpdateOptions{
		InstallDir: dir, Version: "v1.1.0", Yes: true, Repo: defaultUpdateRepo,
	}, srv)

	if code := app.Run(context.Background()); code != ExitOK {
		t.Fatalf("Run() = %d, want %d; stderr=%s", code, ExitOK, stderr.String())
	}

	got, err := os.ReadFile(caddyfile)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(got), "stale caddyfile") {
		t.Fatal("Caddyfile was not re-rendered by update")
	}
	for _, want := range []string{"alfheim.example.com", "auth.example.com", "Generated by alfheim-setup v1.1.0"} {
		if !strings.Contains(string(got), want) {
			t.Errorf("re-rendered Caddyfile does not contain %q", want)
		}
	}

	// The previous Caddyfile is part of the update backup.
	entries, err := os.ReadDir(filepath.Join(dir, ".alfheim-backups"))
	if err != nil || len(entries) != 1 {
		t.Fatalf("expected exactly one backup directory, got %v (err=%v)", entries, err)
	}
	backedUp, err := os.ReadFile(filepath.Join(dir, ".alfheim-backups", entries[0].Name(),
		"infrastructure", "caddy", "Caddyfile"))
	if err != nil {
		t.Fatalf("the old Caddyfile was not backed up: %v", err)
	}
	if !strings.Contains(string(backedUp), "stale caddyfile") {
		t.Errorf("backed-up Caddyfile = %q, want the pre-update content", string(backedUp))
	}

	if n := caddyRestarts(app); n != 1 {
		t.Errorf("caddy restarts = %d, want exactly 1 so the new Caddyfile takes effect", n)
	}
}

func TestUpdateApp_UnchangedCaddyfileDoesNotRestartIngress(t *testing.T) {
	dir := t.TempDir()
	writeExistingInstall(t, dir, "v1.0.0")
	setStrategy(t, dir, "internal")

	srv := startAssetServer(t, updateAssetContents("v1.1.0"))
	defer srv.Close()
	opts := &UpdateOptions{InstallDir: dir, Version: "v1.1.0", Yes: true, Repo: defaultUpdateRepo}

	first, _, stderr := newTestUpdateApp(dir, opts, srv)
	if code := first.Run(context.Background()); code != ExitOK {
		t.Fatalf("first Run() = %d; stderr=%s", code, stderr.String())
	}

	second, _, stderr := newTestUpdateApp(dir, opts, srv)
	if code := second.Run(context.Background()); code != ExitOK {
		t.Fatalf("second Run() = %d; stderr=%s", code, stderr.String())
	}
	if n := caddyRestarts(second); n != 0 {
		t.Errorf("caddy restarts on an update that changed nothing in the Caddyfile = %d, want 0", n)
	}
}

func TestUpdateApp_LeavesCaddyfileAloneWithoutKnownStrategy(t *testing.T) {
	dir := t.TempDir()
	writeExistingInstall(t, dir, "v1.0.0")

	caddyfile := filepath.Join(dir, "infrastructure", "caddy", "Caddyfile")
	if err := os.MkdirAll(filepath.Dir(caddyfile), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(caddyfile, []byte("# hand-tuned\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	srv := startAssetServer(t, updateAssetContents("v1.1.0"))
	defer srv.Close()
	app, _, stderr := newTestUpdateApp(dir, &UpdateOptions{
		InstallDir: dir, Version: "v1.1.0", Yes: true, Repo: defaultUpdateRepo,
	}, srv)

	if code := app.Run(context.Background()); code != ExitOK {
		t.Fatalf("Run() = %d; stderr=%s", code, stderr.String())
	}
	got, err := os.ReadFile(caddyfile)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != "# hand-tuned\n" {
		t.Errorf("Caddyfile = %q, want it untouched when the TLS strategy is unknown", string(got))
	}
	if !strings.Contains(stderr.String(), "--reconfigure") {
		t.Errorf("stderr = %q, want a hint to run --reconfigure", stderr.String())
	}
}
