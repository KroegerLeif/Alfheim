// rerenderCaddyfile regenerates the ingress Caddyfile from the stored
// configuration, so a release that fixes the template (security headers,
// routing) reaches existing installations; compose.prod.yaml and the other
// release assets are fetched, but the Caddyfile is rendered, so without this
// it would stay at whatever the first install wrote. The previous file is
// already in the update backup (assets.GeneratedAssets).
//
// Everything the Caddyfile depends on is read back from .env: the hosts, the
// scheme, ALFHEIM_TLS_STRATEGY, ACME_EMAIL and ALFHEIM_ENABLED_APPS (the
// app and /grafana routes). DNS API tokens are referenced
// as {env.NAME} and never rendered, and a custom certificate's container
// paths are fixed. An installation without a recognised ALFHEIM_TLS_STRATEGY
// (a legacy plain-HTTP .env) is left untouched, since guessing a strategy
// could replace a working ingress with a different one; it is told to run
// --reconfigure. It reports whether the effective content changed; the
// generation stamp is ignored.
func (u *UpdateApp) rerenderCaddyfile(layout paths.Layout, env map[string]string, version string) (bool, error) {
	return rerenderCaddyfile(u.Stdout, u.Stderr, layout, env, version, u.now())
}

// rerenderCaddyfile is the shared implementation behind update and the apps
// command. The enabled set in env decides which app routes are proxied and
// which answer 404 or redirect to the dashboard.
func rerenderCaddyfile(
	stdout, stderr io.Writer, layout paths.Layout, env map[string]string, version string, now time.Time,
) (bool, error) {
	strategy := tls.Strategy(env["ALFHEIM_TLS_STRATEGY"])
	if !strategy.Known() {
		fmt.Fprintf(stderr, "Warning: ALFHEIM_TLS_STRATEGY is %q in .env, so the Caddyfile was not "+
			"regenerated. Run alfheim-setup --reconfigure to pick up ingress changes.\n",
			orDefault(env["ALFHEIM_TLS_STRATEGY"], "unset"))
		return false, nil
	}

	on, err := onboarding.HeadlessConfigFromEnv(env)
	if err != nil {
		return false, err
	}
	set, err := apps.Enabled(env)
	if err != nil {
		return false, err
	}
	renderer, err := templating.NewRenderer()
	if err != nil {
		return false, err
	}
	rendered, err := renderer.RenderCaddyfile(templating.Model{
		Onboarding: on,
		TLS:        tls.Config{Strategy: strategy, ACMEEmail: env["ACME_EMAIL"]},
		Version:    orUnknown(version),
		Generated:  now,
		// An app switched off gets a 404 API and a redirect to the dashboard.
		DisabledApps: set.Disabled(),
	})
	if err != nil {
		return false, fmt.Errorf("regenerate the Caddyfile: %w", err)
	}

	path := layout.Caddyfile()
	previous, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return false, fmt.Errorf("read the current Caddyfile: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, fmt.Errorf("create %s: %w", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, rendered, 0o644); err != nil {
		return false, fmt.Errorf("write the Caddyfile: %w", err)
	}
	fmt.Fprintf(stdout, "Regenerated %s from the stored configuration.\n", path)
	return !bytes.Equal(withoutGeneratedStamp(previous), withoutGeneratedStamp(rendered)), nil
}

// withoutGeneratedStamp drops the "Generated by alfheim-setup <version> on
// <time>" header line, which differs on every render, so that only a change
// to the effective configuration counts as a change (and restarts Caddy).
func withoutGeneratedStamp(content []byte) []byte {
	lines := bytes.Split(content, []byte("\n"))
	kept := lines[:0]
	for _, line := range lines {
		if bytes.HasPrefix(line, []byte("# Generated by alfheim-setup ")) {
			continue
		}
		kept = append(kept, line)
	}
	return bytes.Join(kept, []byte("\n"))
}
